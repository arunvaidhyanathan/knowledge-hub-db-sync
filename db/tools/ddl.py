"""Generate schema.sql from the live catalog with psycopg, without pg_dump.

Object definitions come from the server's own pg_get_* functions, the same ones pg_dump uses.
Output order: schemas, enum types, sequences, functions, tables, views, functions that need
tables, sequence ownership, identity columns, serial defaults, constraints, indexes, foreign
keys, triggers, row-level security, policies, comments. No owners, grants or tablespaces
(like pg_dump --no-owner --no-privileges). Extensions are not emitted (as with pg_dump -n).

Partitions are skipped (parents are kept), matching catalog.json. Object kinds this module
does not reproduce make it fail instead of silently producing an incomplete file.
"""
from __future__ import annotations

import re
from fnmatch import fnmatchcase

import psycopg
from psycopg import rows

HEADER = """-- Generated by db/tools/ddl.py from the live catalog. Do not edit.

SET statement_timeout = 0;
SET lock_timeout = 0;
SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SELECT pg_catalog.set_config('search_path', '', false);
SET check_function_bodies = false;
SET client_min_messages = warning;
SET row_security = off;
"""

NOT_EXT = "NOT EXISTS (SELECT 1 FROM pg_depend e WHERE e.classid = {cls}::regclass AND e.objid = {oid} AND e.deptype = 'e')"

UNSUPPORTED_SQL = f"""
SELECT x FROM (
  SELECT CASE t.typtype WHEN 'd' THEN 'domain ' WHEN 'r' THEN 'range type ' ELSE 'composite type ' END
         || format('%I.%I', n.nspname, t.typname) AS x
  FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = ANY (%(s)s) AND {NOT_EXT.format(cls="'pg_type'", oid='t.oid')}
    AND (t.typtype IN ('d', 'r') OR (t.typtype = 'c' AND (SELECT relkind FROM pg_class WHERE oid = t.typrelid) = 'c'))
  UNION ALL
  SELECT 'aggregate/window function ' || format('%I.%I', n.nspname, p.proname)
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = ANY (%(s)s) AND p.prokind IN ('a', 'w') AND {NOT_EXT.format(cls="'pg_proc'", oid='p.oid')}
  UNION ALL
  SELECT 'operator ' || format('%I.%s', n.nspname, o.oprname)
  FROM pg_operator o JOIN pg_namespace n ON n.oid = o.oprnamespace
  WHERE n.nspname = ANY (%(s)s) AND {NOT_EXT.format(cls="'pg_operator'", oid='o.oid')}
  UNION ALL
  SELECT 'foreign table ' || format('%I.%I', n.nspname, c.relname)
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = ANY (%(s)s) AND c.relkind = 'f' AND {NOT_EXT.format(cls="'pg_class'", oid='c.oid')}
  UNION ALL
  SELECT 'table inheritance ' || format('%I.%I', n.nspname, c.relname)
  FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = ANY (%(s)s) AND NOT c.relispartition
  UNION ALL
  SELECT 'rule ' || format('%I ON %I.%I', r.rulename, n.nspname, c.relname)
  FROM pg_rewrite r JOIN pg_class c ON c.oid = r.ev_class JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = ANY (%(s)s) AND r.rulename <> '_RETURN'
) u ORDER BY 1
"""

RELATIONS_SQL = f"""
SELECT c.oid, format('%I.%I', n.nspname, c.relname) AS fq, n.nspname || '.' || c.relname AS plain,
       c.relkind, c.relispartition, c.relpersistence, c.relrowsecurity, c.relforcerowsecurity,
       array_to_string(c.reloptions, ', ') AS reloptions,
       CASE WHEN c.relkind = 'p' THEN pg_get_partkeydef(c.oid) END AS partkey,
       CASE WHEN c.relkind IN ('v', 'm') THEN pg_get_viewdef(c.oid) END AS viewdef
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY (%(s)s) AND c.relkind IN ('r', 'p', 'v', 'm')
  AND {NOT_EXT.format(cls="'pg_class'", oid='c.oid')}
ORDER BY n.nspname, c.relname
"""

COLUMNS_SQL = """
SELECT a.attrelid AS oid, format('%I', a.attname) AS name, format_type(a.atttypid, a.atttypmod) AS type,
       a.attnotnull AS notnull, a.attidentity AS identity, a.attgenerated AS generated,
       pg_get_expr(d.adbin, d.adrelid) AS def,
       CASE WHEN a.attcollation <> 0 AND a.attcollation <> t.typcollation THEN
         (SELECT format('%I.%I', cn.nspname, co.collname) FROM pg_collation co
          JOIN pg_namespace cn ON cn.oid = co.collnamespace WHERE co.oid = a.attcollation) END AS collation,
       EXISTS (SELECT 1 FROM pg_depend dp JOIN pg_class sq ON sq.oid = dp.objid AND sq.relkind = 'S'
               WHERE dp.refobjid = a.attrelid AND dp.refobjsubid = a.attnum AND dp.deptype = 'a') AS serial
FROM pg_attribute a JOIN pg_type t ON t.oid = a.atttypid
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = ANY (%(oids)s) AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attrelid, a.attnum
"""

SEQUENCES_SQL = f"""
SELECT format('%I.%I', n.nspname, c.relname) AS fq, s.seqtypid::regtype::text AS type,
       s.seqstart AS start, s.seqincrement AS inc, s.seqmin AS min, s.seqmax AS max,
       s.seqcache AS cache, s.seqcycle AS cycle,
       (SELECT dp.refobjid FROM pg_depend dp WHERE dp.objid = c.oid AND dp.classid = 'pg_class'::regclass
          AND dp.deptype IN ('a', 'i') LIMIT 1) AS owner_oid,
       (SELECT format('%I.%I.%I', tn.nspname, tc.relname, ta.attname) FROM pg_depend dp
          JOIN pg_class tc ON tc.oid = dp.refobjid JOIN pg_namespace tn ON tn.oid = tc.relnamespace
          JOIN pg_attribute ta ON ta.attrelid = dp.refobjid AND ta.attnum = dp.refobjsubid
        WHERE dp.objid = c.oid AND dp.classid = 'pg_class'::regclass AND dp.deptype IN ('a', 'i') LIMIT 1) AS owned_by,
       (SELECT format('%I', ta.attname) FROM pg_depend dp
          JOIN pg_attribute ta ON ta.attrelid = dp.refobjid AND ta.attnum = dp.refobjsubid
        WHERE dp.objid = c.oid AND dp.classid = 'pg_class'::regclass AND dp.deptype = 'i' LIMIT 1) AS identity_col
FROM pg_sequence s JOIN pg_class c ON c.oid = s.seqrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY (%(s)s) AND {NOT_EXT.format(cls="'pg_class'", oid='c.oid')}
ORDER BY 1
"""

FUNCTIONS_SQL = f"""
SELECT p.oid, pg_get_functiondef(p.oid) AS def,
       p.prosqlbody IS NOT NULL OR EXISTS (
         SELECT 1 FROM pg_depend dp JOIN pg_type ty ON ty.oid = dp.refobjid
         WHERE dp.classid = 'pg_proc'::regclass AND dp.objid = p.oid
           AND dp.refclassid = 'pg_type'::regclass AND ty.typrelid <> 0) AS needs_tables
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = ANY (%(s)s) AND p.prokind IN ('f', 'p') AND {NOT_EXT.format(cls="'pg_proc'", oid='p.oid')}
ORDER BY n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)
"""

CONSTRAINTS_SQL = """
SELECT con.conrelid AS oid, format('%I', con.conname) AS name, con.contype AS type,
       pg_get_constraintdef(con.oid) AS def, con.convalidated AS validated
FROM pg_constraint con
WHERE con.conrelid = ANY (%(oids)s) AND con.contype IN ('c', 'p', 'u', 'x', 'f') AND con.conislocal
ORDER BY con.conrelid, con.conname
"""

INDEXES_SQL = """
SELECT ic.relname, pg_get_indexdef(i.indexrelid) AS def
FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid JOIN pg_class tc ON tc.oid = i.indrelid
JOIN pg_namespace n ON n.oid = tc.relnamespace
WHERE i.indrelid = ANY (%(oids)s)
  AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid AND c.contype IN ('p', 'u', 'x'))
ORDER BY n.nspname, ic.relname
"""

TRIGGERS_SQL = """
SELECT pg_get_triggerdef(tg.oid) AS def
FROM pg_trigger tg JOIN pg_class c ON c.oid = tg.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE tg.tgrelid = ANY (%(oids)s) AND NOT tg.tgisinternal
ORDER BY n.nspname, c.relname, tg.tgname
"""

POLICIES_SQL = """
SELECT p.polrelid AS oid, format('%I', p.polname) AS name, p.polpermissive AS permissive, p.polcmd AS cmd,
       CASE WHEN p.polroles = '{0}' THEN NULL ELSE
         (SELECT string_agg(quote_ident(r.rolname), ', ' ORDER BY x.ord)
          FROM unnest(p.polroles) WITH ORDINALITY x(oid, ord) JOIN pg_roles r ON r.oid = x.oid) END AS roles,
       pg_get_expr(p.polqual, p.polrelid) AS qual, pg_get_expr(p.polwithcheck, p.polrelid) AS chk
FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE p.polrelid = ANY (%(oids)s)
ORDER BY n.nspname, c.relname, p.polname
"""

ENUMS_SQL = f"""
SELECT format('%I.%I', n.nspname, t.typname) AS fq,
       (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) FROM pg_enum e
        WHERE e.enumtypid = t.oid) AS labels
FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
WHERE n.nspname = ANY (%(s)s) AND t.typtype = 'e' AND {NOT_EXT.format(cls="'pg_type'", oid='t.oid')}
ORDER BY 1
"""

# COMMENT ON for every supported object class whose owner is in scope.
COMMENTS_SQL = """
SELECT stmt FROM (
  SELECT 1 AS o, n.nspname AS k1, '' AS k2, format('COMMENT ON SCHEMA %I IS %L;', n.nspname, d.description) AS stmt
  FROM pg_description d JOIN pg_namespace n ON n.oid = d.objoid
  WHERE d.classoid = 'pg_namespace'::regclass AND n.nspname = ANY (%(s)s)
  UNION ALL
  SELECT 2, n.nspname || '.' || t.typname, '', format('COMMENT ON TYPE %I.%I IS %L;', n.nspname, t.typname, d.description)
  FROM pg_description d JOIN pg_type t ON t.oid = d.objoid JOIN pg_namespace n ON n.oid = t.typnamespace
  WHERE d.classoid = 'pg_type'::regclass AND t.typtype = 'e' AND n.nspname = ANY (%(s)s)
  UNION ALL
  SELECT 3, n.nspname || '.' || p.proname, pg_get_function_identity_arguments(p.oid),
         format('COMMENT ON %s %I.%I(%s) IS %L;', CASE p.prokind WHEN 'p' THEN 'PROCEDURE' ELSE 'FUNCTION' END,
                n.nspname, p.proname, pg_get_function_identity_arguments(p.oid), d.description)
  FROM pg_description d JOIN pg_proc p ON p.oid = d.objoid JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE d.classoid = 'pg_proc'::regclass AND p.oid = ANY (%(fns)s)
  UNION ALL
  SELECT 4, n.nspname || '.' || c.relname, lpad(d.objsubid::text, 5, '0'),
         CASE WHEN d.objsubid = 0 THEN
           format('COMMENT ON %s %I.%I IS %L;',
                  CASE c.relkind WHEN 'v' THEN 'VIEW' WHEN 'm' THEN 'MATERIALIZED VIEW' WHEN 'S' THEN 'SEQUENCE'
                                 WHEN 'i' THEN 'INDEX' WHEN 'I' THEN 'INDEX' ELSE 'TABLE' END,
                  n.nspname, c.relname, d.description)
         ELSE format('COMMENT ON COLUMN %I.%I.%I IS %L;', n.nspname, c.relname,
                     (SELECT attname FROM pg_attribute WHERE attrelid = c.oid AND attnum = d.objsubid), d.description) END
  FROM pg_description d JOIN pg_class c ON c.oid = d.objoid JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE d.classoid = 'pg_class'::regclass AND (c.oid = ANY (%(oids)s)
        OR c.oid IN (SELECT indexrelid FROM pg_index WHERE indrelid = ANY (%(oids)s))
        OR (c.relkind = 'S' AND n.nspname = ANY (%(s)s)))
  UNION ALL
  SELECT 5, n.nspname || '.' || c.relname, con.conname,
         format('COMMENT ON CONSTRAINT %I ON %I.%I IS %L;', con.conname, n.nspname, c.relname, d.description)
  FROM pg_description d JOIN pg_constraint con ON con.oid = d.objoid JOIN pg_class c ON c.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE d.classoid = 'pg_constraint'::regclass AND c.oid = ANY (%(oids)s)
  UNION ALL
  SELECT 6, n.nspname || '.' || c.relname, tg.tgname,
         format('COMMENT ON TRIGGER %I ON %I.%I IS %L;', tg.tgname, n.nspname, c.relname, d.description)
  FROM pg_description d JOIN pg_trigger tg ON tg.oid = d.objoid JOIN pg_class c ON c.oid = tg.tgrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE d.classoid = 'pg_trigger'::regclass AND c.oid = ANY (%(oids)s)
  UNION ALL
  SELECT 7, n.nspname || '.' || c.relname, p.polname,
         format('COMMENT ON POLICY %I ON %I.%I IS %L;', p.polname, n.nspname, c.relname, d.description)
  FROM pg_description d JOIN pg_policy p ON p.oid = d.objoid JOIN pg_class c ON c.oid = p.polrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE d.classoid = 'pg_policy'::regclass AND c.oid = ANY (%(oids)s)
) x ORDER BY o, k1, k2
"""

TYPE_LIMITS = {"smallint": (-32768, 32767), "integer": (-2147483648, 2147483647),
               "bigint": (-9223372036854775808, 9223372036854775807)}
POLICY_CMD = {"r": "SELECT", "a": "INSERT", "w": "UPDATE", "d": "DELETE", "*": None}


def _rows(conn: psycopg.Connection, query: str, **params) -> list[dict]:
    # format('%I ...') in the SQL is not a placeholder; escape every % except %(name)s parameters.
    query = re.sub(r"%(?!\()", "%%", query)
    with conn.cursor(row_factory=rows.dict_row) as cur:
        cur.execute(query, params)
        return cur.fetchall()


def _sequence_options(s: dict, indent: str) -> list[str]:
    lo, hi = TYPE_LIMITS[s["type"]]
    default_min, default_max = (1, hi) if s["inc"] > 0 else (lo, -1)
    lines = [f"{indent}START WITH {s['start']}", f"{indent}INCREMENT BY {s['inc']}",
             f"{indent}NO MINVALUE" if s["min"] == default_min else f"{indent}MINVALUE {s['min']}",
             f"{indent}NO MAXVALUE" if s["max"] == default_max else f"{indent}MAXVALUE {s['max']}",
             f"{indent}CACHE {s['cache']}"]
    if s["cycle"]:
        lines.append(f"{indent}CYCLE")
    return lines


def generate(conn: psycopg.Connection, schemas: list[str], exclude_patterns: list[str]) -> tuple[bytes, dict]:
    """Returns (schema.sql bytes, notes). Must run inside the export's read-only transaction."""
    unsupported = [r["x"] for r in _rows(conn, UNSUPPORTED_SQL, s=schemas)]
    if unsupported:
        raise SystemExit("schema.sql: cannot reproduce these objects without pg_dump: " + "; ".join(unsupported))

    # Qualified names from pg_get_* depend on search_path; pg_dump uses an empty one too.
    with conn.cursor() as cur:
        cur.execute("SELECT current_setting('search_path')")
        original_search_path = cur.fetchone()[0]
        cur.execute("SELECT set_config('search_path', '', true)")

    all_rels = _rows(conn, RELATIONS_SQL, s=schemas)
    excluded = {r["oid"] for r in all_rels if any(fnmatchcase(r["plain"], p) for p in exclude_patterns)}
    partitions = [r for r in all_rels if r["relispartition"]]
    rels = [r for r in all_rels if r["oid"] not in excluded and not r["relispartition"]]
    by_oid = {r["oid"]: r for r in rels}
    oids = list(by_oid)
    tables = [r for r in rels if r["relkind"] in ("r", "p")]
    views = sorted((r for r in rels if r["relkind"] in ("v", "m")), key=lambda r: r["oid"])  # creation order

    cols: dict[int, list[dict]] = {}
    for c in _rows(conn, COLUMNS_SQL, oids=oids):
        cols.setdefault(c["oid"], []).append(c)
    cons: dict[int, list[dict]] = {}
    for c in _rows(conn, CONSTRAINTS_SQL, oids=oids):
        cons.setdefault(c["oid"], []).append(c)
    seqs = [s for s in _rows(conn, SEQUENCES_SQL, s=schemas)
            if s["owner_oid"] is None or s["owner_oid"] in by_oid]
    funcs = _rows(conn, FUNCTIONS_SQL, s=schemas)

    out: list[str] = [HEADER]
    add = out.append

    for r in _rows(conn, "SELECT quote_ident(x) AS q FROM unnest(%(s)s::text[]) x ORDER BY x", s=schemas):
        add(f"CREATE SCHEMA {r['q']};")
    for e in _rows(conn, ENUMS_SQL, s=schemas):
        add(f"CREATE TYPE {e['fq']} AS ENUM (\n    {e['labels']}\n);")
    for s in seqs:
        if s["identity_col"]:
            continue  # created with the identity column below
        add("\n".join([f"CREATE SEQUENCE {s['fq']}", *([f"    AS {s['type']}"] if s["type"] != "bigint" else []),
                       *_sequence_options(s, "    ")]) + ";")

    def function_stmt(f: dict) -> str:
        d = f["def"].rstrip("\n")
        if d.startswith("CREATE OR REPLACE "):
            d = "CREATE " + d[len("CREATE OR REPLACE "):]
        # pg_get_functiondef quotes bodies with $function$/$procedure$; pg_dump uses $$ when the body allows it.
        for tag in ("$function$", "$procedure$"):
            if d.count(tag) == 2 and "$$" not in d:
                d = d.replace(tag, "$$")
        return d + ";"

    for f in funcs:
        if not f["needs_tables"]:
            add(function_stmt(f))

    for t in tables:
        lines = []
        for c in cols.get(t["oid"], []):
            col = f"    {c['name']} {c['type']}"
            if c["collation"]:
                col += f" COLLATE {c['collation']}"
            if c["generated"] == "s":
                col += f" GENERATED ALWAYS AS ({c['def']}) STORED"
            elif c["def"] is not None and not c["serial"]:
                col += f" DEFAULT {c['def']}"
            if c["notnull"]:
                col += " NOT NULL"
            lines.append(col)
        for k in cons.get(t["oid"], []):
            if k["type"] == "c" and k["validated"]:
                lines.append(f"    CONSTRAINT {k['name']} {k['def']}")
        kind = "UNLOGGED TABLE" if t["relpersistence"] == "u" else "TABLE"
        stmt = f"CREATE {kind} {t['fq']} (\n" + ",\n".join(lines) + "\n)"
        if t["partkey"]:
            stmt += f"\nPARTITION BY {t['partkey']}"
        if t["reloptions"]:
            stmt += f"\nWITH ({t['reloptions']})"
        add(stmt + ";")

    for v in views:
        if v["relkind"] == "m":
            add(f"CREATE MATERIALIZED VIEW {v['fq']} AS\n{v['viewdef'].rstrip(';')}\n  WITH NO DATA;")
        else:
            add(f"CREATE VIEW {v['fq']} AS\n{v['viewdef'].rstrip(';')};")

    for f in funcs:
        if f["needs_tables"]:
            add(function_stmt(f))

    for s in seqs:
        if s["owned_by"] and not s["identity_col"]:
            add(f"ALTER SEQUENCE {s['fq']} OWNED BY {s['owned_by']};")
        if s["identity_col"]:
            col = next(c for c in cols[s["owner_oid"]] if c["name"] == s["identity_col"])
            mode = "ALWAYS" if col["identity"] == "a" else "BY DEFAULT"
            add("\n".join([f"ALTER TABLE {by_oid[s['owner_oid']]['fq']} ALTER COLUMN {s['identity_col']} "
                           f"ADD GENERATED {mode} AS IDENTITY (", f"    SEQUENCE NAME {s['fq']}",
                           *_sequence_options(s, "    ")]) + "\n);")

    for t in tables:
        for c in cols.get(t["oid"], []):
            if c["serial"] and c["def"] is not None and not c["identity"]:
                add(f"ALTER TABLE ONLY {t['fq']} ALTER COLUMN {c['name']} SET DEFAULT {c['def']};")

    for t in tables:
        for k in cons.get(t["oid"], []):
            if k["type"] in ("p", "u", "x") or (k["type"] == "c" and not k["validated"]):
                add(f"ALTER TABLE ONLY {t['fq']}\n    ADD CONSTRAINT {k['name']} {k['def']};")
    for i in _rows(conn, INDEXES_SQL, oids=oids):
        add(i["def"] + ";")
    for t in tables:
        for k in cons.get(t["oid"], []):
            if k["type"] == "f":
                only = "" if t["relkind"] == "p" else "ONLY "
                add(f"ALTER TABLE {only}{t['fq']}\n    ADD CONSTRAINT {k['name']} {k['def']};")
    for tg in _rows(conn, TRIGGERS_SQL, oids=oids):
        add(tg["def"] + ";")

    for t in rels:
        if t["relrowsecurity"]:
            add(f"ALTER TABLE {t['fq']} ENABLE ROW LEVEL SECURITY;")
        if t["relforcerowsecurity"]:
            add(f"ALTER TABLE {t['fq']} FORCE ROW LEVEL SECURITY;")
    for p in _rows(conn, POLICIES_SQL, oids=oids):
        stmt = f"CREATE POLICY {p['name']} ON {by_oid[p['oid']]['fq']}"
        if not p["permissive"]:
            stmt += " AS RESTRICTIVE"
        if POLICY_CMD[p["cmd"]]:
            stmt += f" FOR {POLICY_CMD[p['cmd']]}"
        if p["roles"]:
            stmt += f" TO {p['roles']}"
        if p["qual"] is not None:
            stmt += f" USING ({p['qual']})"
        if p["chk"] is not None:
            stmt += f" WITH CHECK ({p['chk']})"
        add(stmt + ";")

    for c in _rows(conn, COMMENTS_SQL, s=schemas, oids=oids, fns=[f["oid"] for f in funcs]):
        add(c["stmt"])

    with conn.cursor() as cur:
        cur.execute("SELECT set_config('search_path', %s, true)", (original_search_path,))
    notes = {"skippedPartitions": len(partitions), "excludedTables": len(excluded)}
    return ("\n\n".join(out).rstrip("\n") + "\n").encode(), notes
